// Command registry writes the filter registry (spec §8.8) as Swift source
// for the app's guidance: the hint line, completions and the cheat sheet
// (app/Sources/LaserdotKit/Registry.generated.swift). The app no longer
// links the core, so this keeps its guidance derived from the registry
// instead of a second copy. Run by app/scripts/build-go.sh; CI fails if the
// committed file is stale.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"os"
	"strings"

	"github.com/jamalxcode/laserdot-go/internal/query"
)

type filter struct {
	// Key as the parser reads it (lang).
	Key string `json:"key"`
	// DisplayKey with the scope prefix the example uses (a.lang).
	DisplayKey  string   `json:"display_key"`
	Section     string   `json:"section"`
	Description string   `json:"description"`
	Example     string   `json:"example"`
	Value       string   `json:"value"`
	Values      []string `json:"values"`
}

type registry struct {
	Sections   []string          `json:"sections"`
	Filters    []filter          `json:"filters"`
	CheatSheet string            `json:"cheat_sheet"`
	TypeWords  map[string]string `json:"type_words"`
}

func valueKind(k query.ValueKind) string {
	switch k {
	case query.VPath:
		return "path"
	case query.VSize:
		return "size"
	case query.VDate:
		return "date"
	case query.VDuration:
		return "duration"
	case query.VBitrate:
		return "bitrate"
	case query.VNumber:
		return "number"
	case query.VBool:
		return "bool"
	case query.VEnum:
		return "enum"
	}
	return "text"
}

func main() {
	var r registry
	for _, s := range query.Sections {
		r.Sections = append(r.Sections, s.Title())
	}
	for _, f := range query.Filters {
		display := f.Key
		if p, _, ok := strings.Cut(f.Example, "."); ok && len(p) == 1 {
			display = p + "." + f.Key
		}
		values := []string{}
		switch f.Value.Kind {
		case query.VEnum:
			values = append(values, f.Value.Values...)
		case query.VBool:
			values = []string{"true", "false"}
		}
		r.Filters = append(r.Filters, filter{
			Key: f.Key, DisplayKey: display, Section: f.Section.Title(), Description: f.Description,
			Example: f.Example, Value: valueKind(f.Value.Kind), Values: values,
		})
	}
	r.CheatSheet = query.CheatSheet()
	r.TypeWords = query.TypeWords()

	var js bytes.Buffer
	enc := json.NewEncoder(&js)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(r); err != nil {
		fmt.Fprintln(os.Stderr, "registry:", err)
		os.Exit(1)
	}
	text := strings.TrimRight(js.String(), "\n")
	if strings.Contains(text, `"""##`) {
		fmt.Fprintln(os.Stderr, "registry: text contains the Swift raw-string delimiter")
		os.Exit(1)
	}
	fmt.Printf("// Code generated by app/scripts/registry from internal/query; DO NOT EDIT.\n"+
		"// Regenerate with app/scripts/build-go.sh.\n\n"+
		"let registryJSON = ##\"\"\"\n%s\n\"\"\"##\n", text)
}
